export function formatPrice(usd: number, currency: SomaliCurrency = 'EVC_PLUS'): string {
  switch (currency) {
    case 'EVC_PLUS':
      return `$${usd.toFixed(2)} EVC`;
    case 'ZAAD':
      return `$${usd.toFixed(2)} Zaad`;
    case 'EDAHAB':
      return `$${usd.toFixed(2)} eDahab`;
    case 'SAHAL':
      return `$${usd.toFixed(2)} Sahal`;
    case 'USD':
    default:
      return `$${usd.toFixed(2)}`;
  }
}

